uint8_t m25p80_sfdp_sst26vf064b(uint32_t addr)
{
    if (addr < sizeof(sfdp_sst26vf064b_header)) {
        return sfdp_sst26vf064b_header[addr];
    }
    if (addr >= 0x100 &&
        addr < 0x100 + sizeof(sfdp_sst26vf064b_sector_map)) {
        return sfdp_sst26vf064b_sector_map[addr - 0x100];
    }
    if (addr >= 0x200 &&
        addr < 0x200 + sizeof(sfdp_sst26vf064b_microchip)) {
        return sfdp_sst26vf064b_microchip[addr - 0x200];
    }
    if (addr >= 0x260 && addr < 0x260 + sizeof(sfdp_sst26vf064b_eui)) {
        return sfdp_sst26vf064b_eui[addr - 0x260];
    }
    return 0xff;
}

